_UPPER = "A-ZĄĆĘŁŃÓŚŹŻ"
_LOWER = "a-ząćęłńóśźż"
_WORD = re.compile(rf"[{_UPPER}][{_LOWER}]+(?:-[{_UPPER}][{_LOWER}]+)?")

# Wyrazy od wielkiej litery, które po imieniu nie są nazwiskiem („Maja Polska”…).
