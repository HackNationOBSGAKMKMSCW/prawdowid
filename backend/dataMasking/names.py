def _female_forms(name: str) -> set[str]:
    stem = name[:-1]
    forms = {name, stem + "y", stem + "ą", stem + "ę", stem + "o", stem + "ie", stem + "i"}
    # Agnieszka → Agnieszce, Ola → Oli, Kasia → Kasi, Magda → Magdzie
    for hard, soft in (("k", "c"), ("g", "dz"), ("d", "dzi"), ("t", "ci"), ("r", "rz"), ("ł", "l")):
        if stem.endswith(hard):
            forms.add(stem[: -len(hard)] + soft + "e")
    if stem.endswith("i"):
        forms.add(stem)  # Kasia → Kasi
    return forms


def _male_forms(name: str) -> set[str]:
    if name.endswith("a"):  # Kuba
        return _female_forms(name) | {name[:-1] + "ie"}
    if name.endswith("i"):  # Antoni
        return {name, name + "ego", name + "emu", name + "m"}
    if name.endswith("y"):  # Jerzy
        stem = name[:-1]
        return {name, stem + "ego", stem + "emu", stem + "ym"}
    stems = {name}
    # Marek → Mark-, Paweł → Pawł-, Tomek → Tomk-
    if len(name) > 3 and name[-2] == "e" and name[-1] in "kł":
        stems.add(name[:-2] + name[-1])
    if name.endswith("ś"):  # Jaś → Jasi-
        stems.add(name[:-1] + "si")
    forms = {name}
    for stem in stems:
        forms |= {stem + end for end in ("a", "owi", "em", "ie", "u", "e", "iem")}
    return forms


@cache
def _first_name_forms() -> frozenset[str]:
    forms: set[str] = set()
    for name in _MALE:
        forms |= _male_forms(name)
    for name in _FEMALE:
        forms |= _female_forms(name)
    return frozenset(f.casefold() for f in forms)


def contains_full_name(text: str) -> bool:
    """Imię ze słownika, a zaraz po nim wyraz od wielkiej litery („Jan Kowalski”, „Kasi Nowak”)."""
    forms = _first_name_forms()
    words = list(_WORD.finditer(text))
    for current, following in zip(words, words[1:], strict=False):
        between = text[current.end() : following.start()]
        if between not in (" ", " "):
            continue
        if current.group().casefold() in forms and following.group().casefold() not in _NOT_SURNAME:
            return True
    return False
